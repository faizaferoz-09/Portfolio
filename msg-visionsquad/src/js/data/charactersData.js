export function getCharactersByCategory(category) {
  if (!category || category === 'all') return CHARACTERS_DATA;
  return CHARACTERS_DATA.filter(c => c.category.toLowerCase() === category.toLowerCase());
}

export function getCharacterById(id) {
  return CHARACTERS_DATA.find(c => c.id === id) || null;
}
